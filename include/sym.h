/**
 * @def DEFAULT_GRAPHICS
 * @brief Plain characters, assuming nothing of the terminal.
 * @note The fallback that always works: if a symbol set is unavailable or unreadable,
 *       the map is still drawable.
 */
/**
 * @def DEFAULT_GRAPHICS
 * @brief 평범한 문자. 터미널에 대해 아무것도 전제하지 않는다.
 * @note 항상 통하는 대비책이다. 심볼 세트를 쓸 수 없거나 읽을 수 없어도 지도는 여전히 그릴 수 있다.
 */
#define DEFAULT_GRAPHICS 0 /* regular characters: '-', '+', &c */
/**
 * @brief Which of the loaded symbol sets is being drawn from.
 *
 * Two are live at once because the Rogue level is drawn differently from the rest of
 * the dungeon, so entering it switches which set is current rather than reloading.
 *
 * @warning @c UNICODESET is deliberately given the value of @c NUM_GRAPHICS -- it is
 *          not one of the sets counted by it, so an array sized by @c NUM_GRAPHICS
 *          cannot be indexed with it.
 */
/**
 * @brief 적재된 심볼 세트 중 어느 것으로 그리고 있는지.
 *
 * 두 개가 동시에 살아 있다. Rogue 레벨이 던전의 나머지와 다르게 그려지므로, 그곳에 들어가는 것은
 * 다시 적재하는 것이 아니라 어느 세트가 현재의 것인지를 바꾸는 일이다.
 *
 * @warning @c UNICODESET 은 의도적으로 @c NUM_GRAPHICS 와 같은 값을 가진다. 그것이 세는 세트에
 *          속하지 않으므로, @c NUM_GRAPHICS 크기로 잡은 배열을 이 값으로 색인할 수 없다.
 */
enum graphics_sets {
        PRIMARYSET = 0,       /* primary graphics set        */
        ROGUESET = 1,         /* rogue graphics set          */
        NUM_GRAPHICS,
        UNICODESET = NUM_GRAPHICS
};

