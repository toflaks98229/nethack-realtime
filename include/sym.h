/**
 * @def MAXDCHARS
 * @brief How many of the symbols are terrain, counted from the ends of that group.
 * @note Derived from the enumerators rather than written as a number, so adding a
 *       terrain symbol inside the group updates the count by itself.
 */
/**
 * @def MAXDCHARS
 * @brief 심볼 중 지형인 것의 개수. 해당 묶음의 양 끝에서 계산된다.
 * @note 숫자로 적지 않고 열거자에서 유도한다. 그래서 묶음 안에 지형 심볼을 추가하면 개수가 저절로
 *       갱신된다.
 */
#define MAXDCHARS (S_water - S_stone + 1) /* mapped dungeon characters */
/**
 * @def MAXTCHARS
 * @brief How many trap symbols there are.
 * @note One fewer than the number of trap types, because @c NO_TRAP is the absence of
 *       a trap and has nothing to draw.
 */
/**
 * @def MAXTCHARS
 * @brief 함정 심볼의 개수.
 * @note 함정 종류의 수보다 하나 적다. @c NO_TRAP 은 함정이 없음을 뜻하므로 그릴 것이 없다.
 */
#define MAXTCHARS (TRAPNUM - 1) /* trap chars */
/** @def MAXECHARS
 *  @brief How many symbols belong to beams, blasts and other transient effects. */
/** @def MAXECHARS
 *  @brief 광선, 폭풍, 그 밖의 일시적 효과에 속한 심볼의 개수. */
#define MAXECHARS (S_expl_br - S_vbeam + 1) /* mapped effects characters */
/**
 * @def MAXEXPCHARS
 * @brief The nine symbols an explosion is drawn from.
 * @note Nine because an explosion covers a three by three area and each position --
 *       corner, edge, centre -- is drawn differently.
 */
/**
 * @def MAXEXPCHARS
 * @brief 폭발을 그리는 데 쓰이는 아홉 개의 심볼.
 * @note 폭발이 3×3 영역을 덮고 모서리, 변, 중앙의 각 위치가 다르게 그려지기 때문에 아홉이다.
 */
#define MAXEXPCHARS 9 /* number of explosion characters */

/**
 * @def DARKROOMSYM
 * @brief What an unlit room square looks like, which depends on the level.
 * @note The Rogue level imitates the original game, where an unlit room square was
 *       indistinguishable from solid rock; elsewhere it has its own appearance.
 * @warning Reads the hero's position, so it cannot be used while describing a level
 *          the hero is not on.
 */
/**
 * @def DARKROOMSYM
 * @brief 불이 켜지지 않은 방 칸의 외형. 레벨에 따라 달라진다.
 * @note Rogue 레벨은 원작을 모방한다. 원작에서는 불 없는 방 칸이 단단한 암반과 구별되지 않았다.
 *       다른 곳에서는 그 자신의 외형을 가진다.
 * @warning 영웅의 위치를 읽는다. 그래서 영웅이 있지 않은 레벨을 기술하는 동안에는 쓸 수 없다.
 */
#define DARKROOMSYM (Is_rogue_level(&u.uz) ? S_stone : S_darkroom)

/**
 * @name Symbol group tests
 * @brief Ask which kind a terrain symbol belongs to.
 *
 * Each is a range comparison against the ends of a group in @c cmap_symbols, which
 * is why those enumerators are grouped and ordered deliberately.
 *
 * @warning The argument is evaluated more than once in every one of these, so an
 *          argument with a side effect will have it applied repeatedly.
 * @warning These accept any number. A value that is not a terrain symbol at all will
 *          still answer true or false rather than reporting the mistake.
 * @{
 */
/**
 * @name 심볼 묶음 검사
 * @brief 지형 심볼이 어느 종류에 속하는지 묻는다.
 *
 * 각각은 @c cmap_symbols 안의 한 묶음의 양 끝과 비교하는 범위 검사다. 그 열거자들이 의도적으로
 * 묶이고 정렬된 이유가 이것이다.
 *
 * @warning 이들 모두에서 인자가 한 번 넘게 평가된다. 그래서 부작용이 있는 인자는 그 부작용이 거듭
 *          적용된다.
 * @warning 어떤 숫자든 받는다. 지형 심볼이 전혀 아닌 값도 잘못을 알리지 않고 참이나 거짓으로
 *          답한다.
 * @{
 */
#define is_cmap_trap(i) ((i) >= S_arrow_trap && (i) < S_arrow_trap + MAXTCHARS)
#define is_cmap_drawbridge(i) ((i) >= S_vodbridge && (i) <= S_hcdbridge)
#define is_cmap_door(i) ((i) >= S_vodoor && (i) <= S_hcdoor)
#define is_cmap_wall(i) ((i) >= S_stone && (i) <= S_trwall)
#define is_cmap_room(i) ((i) >= S_room && (i) <= S_darkroom)
#define is_cmap_corr(i) ((i) >= S_corr && (i) <= S_litcorr)
#define is_cmap_furniture(i) ((i) >= S_upstair && (i) <= S_fountain)
#define is_cmap_water(i) ((i) == S_pool || (i) == S_water)
#define is_cmap_lava(i) ((i) == S_lava || (i) == S_lavawall)
#define is_cmap_stairs(i) ((i) >= S_upstair && (i) <= S_brdnladder)
#define is_cmap_engraving(i) ((i) == S_engroom || (i) == S_engrcorr)
/** @} */

/**
 * @brief Symbols that stand for a state of knowledge rather than a thing.
 *
 * A square the hero has not seen, a monster known to be somewhere but not seen, the
 * mark that says "this is your pet" -- none of these is terrain or a monster class,
 * but each needs an appearance the player can change.
 *
 * @note @c SYM_NOTHING and @c SYM_UNEXPLORED differ: one is a square known to hold
 *       nothing, the other a square nothing is known about.
 */
/**
 * @brief 사물이 아니라 앎의 상태를 나타내는 심볼들.
 *
 * 영웅이 보지 못한 칸, 어딘가에 있다고 알지만 보이지 않는 몬스터, "이것은 당신의 애완동물"이라고
 * 알리는 표시. 어느 것도 지형이나 몬스터 계열이 아니지만, 각각 플레이어가 바꿀 수 있는 외형을
 * 필요로 한다.
 *
 * @note @c SYM_NOTHING 과 @c SYM_UNEXPLORED 는 다르다. 하나는 아무것도 없다고 알려진 칸이고,
 *       다른 하나는 아무것도 알려지지 않은 칸이다.
 */
/* misc symbol definitions */
enum misc_symbols {
        SYM_NOTHING = 0,
        SYM_UNEXPLORED = 1,
        SYM_BOULDER = 2,
        SYM_INVISIBLE = 3,
        SYM_PET_OVERRIDE = 4,
        SYM_HERO_OVERRIDE = 5,
        MAXOTHER
};

